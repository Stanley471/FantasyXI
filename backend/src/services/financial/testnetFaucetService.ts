/**
 * Testnet faucet for local development and staging onboarding (issue #558).
 *
 * Funds a Stellar testnet account through Friendbot (10,000 XLM), optionally
 * creates the USDC trustline and mints test USDC from a custom test issuer, and
 * verifies the resulting balances on Horizon.
 *
 * Safety:
 * - Never available when NODE_ENV is "production" (see isFaucetAllowed and the
 *   404 guard in routes/dev.routes.ts) or when the configured network is not TESTNET.
 * - Server-side trustline and mint steps need the account's secret key, so they
 *   only run for accounts generated here (`generate: true`). The secret of a
 *   generated testnet account is returned once and never stored or logged.
 *   Existing addresses are only funded; they must add the trustline themselves.
 */

import {
  Asset,
  BASE_FEE,
  Keypair,
  Operation,
  StrKey,
  TransactionBuilder,
} from "@stellar/stellar-sdk";

export const DEFAULT_FRIENDBOT_URL = "https://friendbot.stellar.org";
export const DEFAULT_TEST_USDC_MINT_AMOUNT = "1000.0000000";

export class FaucetError extends Error {
  constructor(
    public readonly status: number,
    message: string
  ) {
    super(message);
  }
}

export interface FaucetBalances {
  xlm: string | null;
  usdc: string | null;
}

export interface FaucetResult {
  address: string;
  /** Only present for accounts generated by the faucet (testnet only). */
  secret?: string;
  friendbot: "funded" | "already_funded";
  trustline: "established" | "exists" | "not_configured" | "requires_account_signature";
  usdcMinted: string | null;
  balances: FaucetBalances;
}

/** The slice of Horizon the faucet uses. */
export interface FaucetHorizon {
  loadAccount(address: string): Promise<any>;
  submitTransaction(tx: any): Promise<unknown>;
}

export interface TestnetFaucetOptions {
  horizon: () => FaucetHorizon;
  fetchFn?: typeof fetch;
  friendbotUrl?: string;
  network: string;
  networkPassphrase: string;
  usdcAssetCode: string;
  usdcIssuer: string;
  /** Secret key of the custom test USDC issuer (STELLAR_TEST_USDC_ISSUER_SECRET). */
  issuerSecret?: string;
  mintAmount?: string;
}

/** The faucet is off in production regardless of any other setting. */
export function isFaucetAllowed(env: NodeJS.ProcessEnv = process.env): boolean {
  return env.NODE_ENV !== "production";
}

function usdcBalanceOf(account: any, asset: Asset | null): string | null {
  if (!asset) return null;
  const line = (account.balances ?? []).find(
    (b: any) => b.asset_code === asset.getCode() && b.asset_issuer === asset.getIssuer()
  );
  return line ? String(line.balance) : null;
}

function nativeBalanceOf(account: any): string | null {
  const line = (account.balances ?? []).find((b: any) => b.asset_type === "native");
  return line ? String(line.balance) : null;
}

export class TestnetFaucetService {
  private readonly fetchFn: typeof fetch;
  private readonly friendbotUrl: string;
  private readonly usdc: Asset | null;
  private readonly issuerKeypair: Keypair | null;

  constructor(private readonly options: TestnetFaucetOptions) {
    this.fetchFn = options.fetchFn ?? fetch;
    this.friendbotUrl = (options.friendbotUrl ?? DEFAULT_FRIENDBOT_URL).replace(/\/$/, "");
    // A classic trustline needs a G... issuer account; a contract-based USDC cannot be used here.
    this.usdc = StrKey.isValidEd25519PublicKey(options.usdcIssuer)
      ? new Asset(options.usdcAssetCode, options.usdcIssuer)
      : null;
    this.issuerKeypair = this.resolveIssuerKeypair();
  }

  private resolveIssuerKeypair(): Keypair | null {
    if (!this.options.issuerSecret || !this.usdc) return null;
    try {
      const keypair = Keypair.fromSecret(this.options.issuerSecret);
      return keypair.publicKey() === this.options.usdcIssuer ? keypair : null;
    } catch {
      return null;
    }
  }

  public async fund(input: { address?: string; generate?: boolean }): Promise<FaucetResult> {
    if (this.options.network !== "TESTNET") {
      throw new FaucetError(400, "The faucet only works on the Stellar TESTNET network");
    }

    let keypair: Keypair | null = null;
    let address = input.address;
    if (input.generate) {
      keypair = Keypair.random();
      address = keypair.publicKey();
    }
    if (!address || !StrKey.isValidEd25519PublicKey(address)) {
      throw new FaucetError(400, "A valid Stellar public key (G...) or generate=true is required");
    }

    const friendbot = await this.callFriendbot(address);
    const horizon = this.options.horizon();

    let trustline: FaucetResult["trustline"] = "not_configured";
    let usdcMinted: string | null = null;

    if (this.usdc) {
      if (keypair) {
        trustline = await this.establishTrustline(horizon, keypair);
        usdcMinted = await this.mintUsdc(horizon, address);
      } else {
        const existing = usdcBalanceOf(await horizon.loadAccount(address), this.usdc);
        trustline = existing !== null ? "exists" : "requires_account_signature";
      }
    }

    // Verify on Horizon rather than trusting the Friendbot response.
    const account = await horizon.loadAccount(address);
    return {
      address,
      ...(keypair ? { secret: keypair.secret() } : {}),
      friendbot,
      trustline,
      usdcMinted,
      balances: { xlm: nativeBalanceOf(account), usdc: usdcBalanceOf(account, this.usdc) },
    };
  }

  private async callFriendbot(address: string): Promise<FaucetResult["friendbot"]> {
    let response: Response;
    try {
      response = await this.fetchFn(`${this.friendbotUrl}/?addr=${encodeURIComponent(address)}`);
    } catch (error) {
      throw new FaucetError(502, `Friendbot is unreachable: ${(error as Error).message}`);
    }
    if (response.ok) return "funded";

    const body = await response.text().catch(() => "");
    // Friendbot reports an account that already exists with a 400.
    if (response.status === 400 && /already|op_already_exists|createAccountAlreadyExist/i.test(body)) {
      return "already_funded";
    }
    throw new FaucetError(502, `Friendbot returned HTTP ${response.status}`);
  }

  private async establishTrustline(horizon: FaucetHorizon, keypair: Keypair): Promise<FaucetResult["trustline"]> {
    const account = await horizon.loadAccount(keypair.publicKey());
    if (usdcBalanceOf(account, this.usdc) !== null) return "exists";
    const tx = new TransactionBuilder(account, {
      fee: BASE_FEE,
      networkPassphrase: this.options.networkPassphrase,
    })
      .addOperation(Operation.changeTrust({ asset: this.usdc! }))
      .setTimeout(60)
      .build();
    tx.sign(keypair);
    await horizon.submitTransaction(tx);
    return "established";
  }

  private async mintUsdc(horizon: FaucetHorizon, destination: string): Promise<string | null> {
    if (!this.issuerKeypair) return null;
    const amount = this.options.mintAmount ?? DEFAULT_TEST_USDC_MINT_AMOUNT;
    const issuerAccount = await horizon.loadAccount(this.issuerKeypair.publicKey());
    const tx = new TransactionBuilder(issuerAccount, {
      fee: BASE_FEE,
      networkPassphrase: this.options.networkPassphrase,
    })
      .addOperation(Operation.payment({ destination, asset: this.usdc!, amount }))
      .setTimeout(60)
      .build();
    tx.sign(this.issuerKeypair);
    await horizon.submitTransaction(tx);
    return amount;
  }
}

/** Builds the faucet from environment and the Stellar config. */
export async function createTestnetFaucetService(): Promise<TestnetFaucetService> {
  const { getHorizonServer, stellarConfig } = await import("../../config/stellar.js");
  return new TestnetFaucetService({
    horizon: () => getHorizonServer() as unknown as FaucetHorizon,
    friendbotUrl: process.env.STELLAR_FRIENDBOT_URL,
    network: stellarConfig.network,
    networkPassphrase: stellarConfig.networkPassphrase,
    usdcAssetCode: stellarConfig.usdcAssetCode,
    usdcIssuer: stellarConfig.usdcIssuer,
    issuerSecret: process.env.STELLAR_TEST_USDC_ISSUER_SECRET,
    mintAmount: process.env.STELLAR_TEST_USDC_MINT_AMOUNT,
  });
}
